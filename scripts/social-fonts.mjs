// Vendors the brand faces the social art embeds, and generates the advance-width
// table its SVG text wrapper measures with (TASK-social-art-foundations.md §2.1).
// Run with `pnpm social:fonts` after bumping either @fontsource package.
import { copyFile, mkdir, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import * as fontkit from "fontkit";

const require = createRequire(import.meta.url);
const root = join(dirname(new URL(import.meta.url).pathname), "..");
const out = join(root, "public/fonts/social");
const FACES = [
  { key: "sans400", pkg: "@fontsource/space-grotesk", file: "space-grotesk-latin-400-normal.woff2" },
  { key: "sans500", pkg: "@fontsource/space-grotesk", file: "space-grotesk-latin-500-normal.woff2" },
  { key: "sans700", pkg: "@fontsource/space-grotesk", file: "space-grotesk-latin-700-normal.woff2" },
  { key: "mono500", pkg: "@fontsource/jetbrains-mono", file: "jetbrains-mono-latin-500-normal.woff2" },
  { key: "mono700", pkg: "@fontsource/jetbrains-mono", file: "jetbrains-mono-latin-700-normal.woff2" },
];

await mkdir(out, { recursive: true });
const metrics = {};
for (const face of FACES) {
  const pkgDir = dirname(require.resolve(`${face.pkg}/package.json`));
  const source = join(pkgDir, "files", face.file);
  await copyFile(source, join(out, face.file));
  await copyFile(join(pkgDir, "LICENSE"), join(out, `${face.pkg.split("/")[1]}-LICENSE.txt`));
  const font = fontkit.openSync(source);
  const widths = {};
  for (const code of font.characterSet) {
    const glyph = font.glyphForCodePoint(code);
    if (glyph.id) widths[String.fromCodePoint(code)] = Math.round((glyph.advanceWidth / font.unitsPerEm) * 1000) / 1000;
  }
  metrics[face.key] = { file: face.file, fallback: widths["n"] ?? 0.6, widths };
}

const header = "// Generated by scripts/social-fonts.mjs — do not edit by hand.\n// Advance widths in em per character for the faces embedded in social art.\n";
await writeFile(join(root, "src/lib/social-font-metrics.ts"), `${header}export const SOCIAL_FONT_METRICS = ${JSON.stringify(metrics)} as const;\n`);
console.log(Object.entries(metrics).map(([key, value]) => `${key}: ${Object.keys(value.widths).length} glyphs`).join("\n"));
