// Precomputes ASCII glyph grids for the approved portfolio screenshots
// (TASK-social-art-signatures.md §2.1). The browser renders these synchronously;
// it never decodes a screenshot just to draw its ASCII version.
// Run with `pnpm social:ascii` after editing src/lib/social-art-images.json.
import { readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import sharp from "sharp";
import { SCREENSHOT_COLS, SCREENSHOT_MAX_ROWS, asciiFromLuminance } from "../src/lib/social-ascii.ts";

const root = join(dirname(new URL(import.meta.url).pathname), "..");
const images = JSON.parse(await readFile(join(root, "src/lib/social-art-images.json"), "utf8"));
const grids = {};
for (const path of Object.keys(images)) {
  const { data, info } = await sharp(join(root, "public", path)).greyscale().resize({ width: 560, withoutEnlargement: true }).raw().toBuffer({ resolveWithObject: true });
  const luma = Float32Array.from(data, (v) => v / 255);
  grids[path] = asciiFromLuminance(luma, info.width, info.height, SCREENSHOT_COLS, SCREENSHOT_MAX_ROWS);
}
const header = "// Generated by scripts/social-ascii.mjs — do not edit by hand.\n";
await writeFile(join(root, "src/lib/social-ascii-data.ts"), `${header}export const PRESET_ASCII: Record<string, string> = ${JSON.stringify(grids, null, 0)};\n`);
console.log(Object.entries(grids).map(([path, grid]) => `${path}: ${grid.length} chars`).join("\n"));
